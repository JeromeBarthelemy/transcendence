import threading
from http.client import InvalidURL
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.error import URLError

import pytest

from club.models import Chunk, Document, Season, SourceUpdate, User
from club.rag import ingest_document
from club.sources import (
    accept_update,
    check_document,
    content_hash,
    fetch_page,
    latest_documents,
    summarize,
)

from .test_rag import REAL_HTML_EXCERPT

MANUAL_URL = "https://ftc.example/manual.html"
CHANGED_HTML = REAL_HTML_EXCERPT.replace(
    "elements is prohibited.", "elements is prohibited, even briefly."
)


def season():
    return Season.objects.create(start_year=2026, game_name="BioBuzz")


def manual_copy(the_season, text=REAL_HTML_EXCERPT):
    return ingest_document(
        season=the_season,
        source=Document.Source.GAME_MANUAL,
        title="Manuel de jeu",
        text=text,
        url=MANUAL_URL,
        content_hash=content_hash(text),
    )


def serve(monkeypatch, page):
    monkeypatch.setattr("club.sources.fetch_page", lambda url: page)


# --- comparing ---


def test_identical_passages_summarise_to_nothing_changed():
    passages = [("G101", "one"), ("G102", "two")]

    summary = summarize(passages, passages)

    assert summary["added"] == summary["removed"] == summary["changed"] == 0
    assert summary["references"] == []


def test_a_changed_passage_is_counted_and_named_by_its_reference():
    current = [("G101", "one"), ("G102", "two")]
    candidate = [("G101", "one"), ("G102", "two, amended")]

    summary = summarize(current, candidate)

    assert summary["changed"] == 1
    assert summary["references"] == ["G102"]


def test_added_and_removed_passages_are_counted_separately():
    current = [("G101", "one"), ("G102", "two"), ("G103", "three")]
    candidate = [("G101", "one"), ("G103", "three"), ("G104", "four")]

    summary = summarize(current, candidate)

    assert summary["removed"] == 1
    assert summary["added"] == 1
    assert set(summary["references"]) == {"G102", "G104"}


# --- checking ---


def test_an_unchanged_page_only_records_that_it_was_checked(monkeypatch):
    the_season = season()
    copy = manual_copy(the_season)
    serve(monkeypatch, REAL_HTML_EXCERPT)

    outcome = check_document(copy)

    assert outcome.status == "unchanged"
    copy.refresh_from_db()
    assert copy.checked_at is not None
    assert not SourceUpdate.objects.exists()


def test_a_changed_passage_becomes_a_pending_update_and_nothing_is_replaced(
    monkeypatch,
):
    the_season = season()
    copy = manual_copy(the_season)
    serve(monkeypatch, CHANGED_HTML)

    outcome = check_document(copy)

    assert outcome.status == "pending"
    update = SourceUpdate.objects.get(season=the_season)
    assert update.summary["changed"] == 1
    assert "G102" in update.summary["references"]
    assert [document.pk for document in latest_documents()] == [copy.pk]


def test_bytes_that_change_without_changing_a_passage_are_not_an_update(monkeypatch):
    the_season = season()
    copy = manual_copy(the_season)
    page = REAL_HTML_EXCERPT + "\n<!-- regenerated by the publisher -->"
    serve(monkeypatch, page)

    outcome = check_document(copy)

    assert outcome.status == "unchanged"
    assert not SourceUpdate.objects.exists()
    copy.refresh_from_db()
    assert copy.content_hash == content_hash(page)


def test_a_page_that_cannot_be_fetched_is_reported_not_raised(monkeypatch):
    copy = manual_copy(season())

    def unreachable(url):
        raise URLError("le site ne répond pas")

    monkeypatch.setattr("club.sources.fetch_page", unreachable)

    outcome = check_document(copy)

    assert outcome.status == "error"
    assert "ne répond pas" in outcome.detail


def test_a_malformed_url_is_reported_not_raised(monkeypatch):
    # urllib raises http.client.InvalidURL for a URL control character
    # (an unencoded space, say) before it ever reaches the network — a
    # different exception type than a reachable server refusing the
    # request, but the same "tell the admin" outcome.
    copy = manual_copy(season())

    def malformed(url):
        raise InvalidURL("URL can't contain control characters")

    monkeypatch.setattr("club.sources.fetch_page", malformed)

    outcome = check_document(copy)

    assert outcome.status == "error"
    assert "control characters" in outcome.detail


# --- accepting ---


def test_accepting_replaces_the_searched_copy_and_keeps_the_old_passages(monkeypatch):
    the_season = season()
    old = manual_copy(the_season)
    serve(monkeypatch, CHANGED_HTML)
    check_document(old)
    update = SourceUpdate.objects.get(season=the_season)
    old_passages = Chunk.objects.filter(document=old).count()

    new = accept_update(update)

    assert [document.pk for document in latest_documents()] == [new.pk]
    assert new.content_hash == update.content_hash
    assert not SourceUpdate.objects.exists()
    assert Chunk.objects.filter(document=old).count() == old_passages


